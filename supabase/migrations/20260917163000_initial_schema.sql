create extension if not exists citext with schema extensions;

create type public.post_visibility as enum ('public', 'followers', 'private');
create type public.deck_visibility as enum ('public', 'unlisted', 'private');
create type public.deck_zone as enum ('commander', 'mainboard', 'sideboard', 'maybeboard');
create type public.report_status as enum ('open', 'reviewing', 'resolved', 'dismissed');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  handle extensions.citext not null unique check (handle ~ '^[a-zA-Z0-9_]{3,30}$'),
  display_name text not null check (char_length(display_name) between 1 and 60),
  bio text not null default '' check (char_length(bio) <= 300),
  avatar_url text,
  favorite_formats text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.follows (
  follower_id uuid not null references public.profiles(id) on delete cascade,
  followed_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, followed_id),
  check (follower_id <> followed_id)
);

create table public.blocks (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create table public.mutes (
  muter_id uuid not null references public.profiles(id) on delete cascade,
  muted_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (muter_id, muted_id),
  check (muter_id <> muted_id)
);

create table public.posts (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 500),
  reply_to_id uuid references public.posts(id) on delete cascade,
  visibility public.post_visibility not null default 'public',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.post_likes (
  post_id uuid not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table public.reposts (
  post_id uuid not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table public.decks (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 100),
  format text not null check (format in ('commander', 'standard', 'modern', 'pioneer')),
  description text not null default '' check (char_length(description) <= 2000),
  visibility public.deck_visibility not null default 'public',
  current_version integer not null default 1 check (current_version >= 1),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.deck_versions (
  id uuid primary key default gen_random_uuid(),
  deck_id uuid not null references public.decks(id) on delete cascade,
  version integer not null check (version >= 1),
  note text not null default '' check (char_length(note) <= 500),
  created_at timestamptz not null default now(),
  unique (deck_id, version)
);

create table public.deck_cards (
  id bigint generated by default as identity primary key,
  deck_version_id uuid not null references public.deck_versions(id) on delete cascade,
  zone public.deck_zone not null default 'mainboard',
  quantity smallint not null check (quantity between 1 and 100),
  oracle_id uuid,
  scryfall_id uuid not null,
  card_name text not null,
  image_small_url text,
  image_normal_url text,
  unique (deck_version_id, zone, scryfall_id)
);

create table public.post_decks (
  post_id uuid primary key references public.posts(id) on delete cascade,
  deck_version_id uuid not null references public.deck_versions(id) on delete restrict
);

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  post_id uuid references public.posts(id) on delete cascade,
  reported_user_id uuid references public.profiles(id) on delete cascade,
  reason text not null check (char_length(reason) between 3 and 500),
  status public.report_status not null default 'open',
  created_at timestamptz not null default now(),
  check ((post_id is not null)::integer + (reported_user_id is not null)::integer = 1)
);

create index posts_author_created_idx on public.posts (author_id, created_at desc);
create index posts_created_idx on public.posts (created_at desc, id desc);
create index follows_followed_idx on public.follows (followed_id, follower_id);
create index decks_owner_updated_idx on public.decks (owner_id, updated_at desc);
create index deck_versions_deck_idx on public.deck_versions (deck_id, version desc);
create index deck_cards_version_zone_idx on public.deck_cards (deck_version_id, zone);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
create trigger posts_set_updated_at before update on public.posts
for each row execute function public.set_updated_at();
create trigger decks_set_updated_at before update on public.decks
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, handle, display_name)
  values (
    new.id,
    'mage_' || left(replace(new.id::text, '-', ''), 10),
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(new.email, '@', 1), 'Nuevo mago')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

