create policy "profiles are public" on public.profiles for select using (true);
create policy "users update own profile" on public.profiles for update to authenticated
using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create policy "follows are public" on public.follows for select using (true);
create policy "users create own follows" on public.follows for insert to authenticated
with check ((select auth.uid()) = follower_id);
create policy "users delete own follows" on public.follows for delete to authenticated
using ((select auth.uid()) = follower_id);

create policy "users view own blocks" on public.blocks for select to authenticated
using ((select auth.uid()) = blocker_id);
create policy "users create own blocks" on public.blocks for insert to authenticated
with check ((select auth.uid()) = blocker_id);
create policy "users delete own blocks" on public.blocks for delete to authenticated
using ((select auth.uid()) = blocker_id);

create policy "users view own mutes" on public.mutes for select to authenticated
using ((select auth.uid()) = muter_id);
create policy "users create own mutes" on public.mutes for insert to authenticated
with check ((select auth.uid()) = muter_id);
create policy "users delete own mutes" on public.mutes for delete to authenticated
using ((select auth.uid()) = muter_id);

create policy "visible posts can be read" on public.posts for select using (
  visibility = 'public'
  or author_id = (select auth.uid())
  or (
    visibility = 'followers'
    and exists (
      select 1 from public.follows
      where follower_id = (select auth.uid()) and followed_id = author_id
    )
  )
);
create policy "users create own posts" on public.posts for insert to authenticated
with check ((select auth.uid()) = author_id);
create policy "users update own posts" on public.posts for update to authenticated
using ((select auth.uid()) = author_id) with check ((select auth.uid()) = author_id);
create policy "users delete own posts" on public.posts for delete to authenticated
using ((select auth.uid()) = author_id);

create policy "post likes are readable" on public.post_likes for select using (true);
create policy "users create own likes" on public.post_likes for insert to authenticated
with check ((select auth.uid()) = user_id);
create policy "users delete own likes" on public.post_likes for delete to authenticated
using ((select auth.uid()) = user_id);

create policy "reposts are readable" on public.reposts for select using (true);
create policy "users create own reposts" on public.reposts for insert to authenticated
with check ((select auth.uid()) = user_id);
create policy "users delete own reposts" on public.reposts for delete to authenticated
using ((select auth.uid()) = user_id);

create policy "visible decks can be read" on public.decks for select using (
  visibility in ('public', 'unlisted') or owner_id = (select auth.uid())
);
create policy "users create own decks" on public.decks for insert to authenticated
with check ((select auth.uid()) = owner_id);
create policy "users update own decks" on public.decks for update to authenticated
using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy "users delete own decks" on public.decks for delete to authenticated
using ((select auth.uid()) = owner_id);

create policy "visible deck versions can be read" on public.deck_versions for select using (
  exists (
    select 1 from public.decks
    where decks.id = deck_versions.deck_id
      and (decks.visibility in ('public', 'unlisted') or decks.owner_id = (select auth.uid()))
  )
);
create policy "owners create deck versions" on public.deck_versions for insert to authenticated
with check (exists (select 1 from public.decks where decks.id = deck_id and decks.owner_id = (select auth.uid())));

create policy "visible deck cards can be read" on public.deck_cards for select using (
  exists (
    select 1 from public.deck_versions
    join public.decks on decks.id = deck_versions.deck_id
    where deck_versions.id = deck_cards.deck_version_id
      and (decks.visibility in ('public', 'unlisted') or decks.owner_id = (select auth.uid()))
  )
);
create policy "owners create deck cards" on public.deck_cards for insert to authenticated
with check (
  exists (
    select 1 from public.deck_versions
    join public.decks on decks.id = deck_versions.deck_id
    where deck_versions.id = deck_version_id and decks.owner_id = (select auth.uid())
  )
);

create policy "visible post decks can be read" on public.post_decks for select using (
  exists (select 1 from public.posts where posts.id = post_decks.post_id)
);
create policy "authors attach deck versions" on public.post_decks for insert to authenticated
with check (
  exists (select 1 from public.posts where posts.id = post_id and posts.author_id = (select auth.uid()))
  and exists (
    select 1 from public.deck_versions
    join public.decks on decks.id = deck_versions.deck_id
    where deck_versions.id = deck_version_id and decks.owner_id = (select auth.uid())
  )
);

create policy "users create reports" on public.reports for insert to authenticated
with check ((select auth.uid()) = reporter_id);
create policy "users view own reports" on public.reports for select to authenticated
using ((select auth.uid()) = reporter_id);

