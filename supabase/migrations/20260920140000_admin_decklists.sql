create function public.get_admin_decks(
  p_query text default '',
  p_format text default 'all',
  p_state text default 'all',
  p_limit integer default 30,
  p_offset integer default 0
)
returns table (
  id uuid,
  owner_id uuid,
  owner_handle text,
  owner_name text,
  title text,
  format text,
  format_name text,
  description text,
  visibility text,
  moderation_status text,
  moderation_reason text,
  current_version integer,
  version_count bigint,
  total_cards bigint,
  post_count bigint,
  created_at timestamptz,
  updated_at timestamptz,
  archived_at timestamptz,
  archive_reason text,
  total_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if p_state not in ('all', 'active', 'hidden', 'archived') then raise exception 'Invalid deck state'; end if;

  return query
  with deck_rows as (
    select
      deck.id as id,
      deck.owner_id as owner_id,
      profile.handle::text as owner_handle,
      profile.display_name as owner_name,
      deck.title as title,
      deck.format as format,
      format.name as format_name,
      deck.description as description,
      deck.visibility::text as visibility,
      deck.moderation_status::text as moderation_status,
      deck.moderation_reason as moderation_reason,
      deck.current_version as current_version,
      (select count(*) from public.deck_versions version where version.deck_id = deck.id) as version_count,
      coalesce((
        select sum(card.quantity)::bigint
        from public.deck_versions version
        join public.deck_cards card on card.deck_version_id = version.id
        where version.deck_id = deck.id and version.version = deck.current_version
      ), 0) as total_cards,
      (select count(*) from public.post_decks attachment
        join public.deck_versions version on version.id = attachment.deck_version_id
        where version.deck_id = deck.id) as post_count,
      deck.created_at as created_at,
      deck.updated_at as updated_at,
      deck.archived_at as archived_at,
      deck.archive_reason as archive_reason
    from public.decks deck
    join public.profiles profile on profile.id = deck.owner_id
    join public.formats format on format.slug = deck.format
  ), filtered as (
    select * from deck_rows deck_row
    where (
      trim(coalesce(p_query, '')) = ''
      or deck_row.title ilike '%' || trim(p_query) || '%'
      or deck_row.owner_handle ilike '%' || trim(p_query) || '%'
      or deck_row.owner_name ilike '%' || trim(p_query) || '%'
    )
      and (p_format = 'all' or deck_row.format = p_format)
      and (
        p_state = 'all'
        or (p_state = 'active' and deck_row.archived_at is null and deck_row.moderation_status = 'visible')
        or (p_state = 'hidden' and deck_row.archived_at is null and deck_row.moderation_status = 'hidden')
        or (p_state = 'archived' and deck_row.archived_at is not null)
      )
  )
  select filtered.*, count(*) over() as total_count
  from filtered
  order by filtered.archived_at nulls first, filtered.updated_at desc, filtered.id
  limit least(greatest(p_limit, 1), 100)
  offset greatest(p_offset, 0);
end;
$$;

create function public.admin_create_deck(
  p_owner_id uuid,
  p_title text,
  p_format text,
  p_visibility public.deck_visibility,
  p_description text,
  p_note text,
  p_cards jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  new_deck_id uuid;
  new_version_id uuid;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if not exists (select 1 from public.profiles where id = p_owner_id) then raise exception 'Owner not found'; end if;
  perform public.validate_deck_card_payload(p_format, p_cards);

  insert into public.decks (owner_id, title, format, description, visibility)
  values (p_owner_id, trim(p_title), p_format, trim(coalesce(p_description, '')), p_visibility)
  returning decks.id into new_deck_id;
  insert into public.deck_versions (deck_id, version, note)
  values (new_deck_id, 1, trim(coalesce(p_note, '')))
  returning deck_versions.id into new_version_id;
  perform public.insert_deck_version_cards(new_version_id, p_cards);
  insert into public.deck_admin_audit_log (deck_id, actor_id, action, metadata)
  values (new_deck_id, actor, 'deck_created', jsonb_build_object('owner_id', p_owner_id, 'version_id', new_version_id));
  return new_deck_id;
end;
$$;

create function public.admin_create_deck_version(p_deck_id uuid, p_note text, p_cards jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := (select auth.uid());
  deck_row public.decks%rowtype;
  new_version integer;
  new_version_id uuid;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into deck_row from public.decks where id = p_deck_id for update;
  if not found then raise exception 'Deck not found'; end if;
  if deck_row.archived_at is not null then raise exception 'Archived deck cannot receive versions'; end if;
  perform public.validate_deck_card_payload(deck_row.format, p_cards);
  select coalesce(max(version), 0) + 1 into new_version from public.deck_versions where deck_id = p_deck_id;
  insert into public.deck_versions (deck_id, version, note)
  values (p_deck_id, new_version, trim(coalesce(p_note, '')))
  returning id into new_version_id;
  perform public.insert_deck_version_cards(new_version_id, p_cards);
  update public.decks set current_version = new_version where id = p_deck_id;
  insert into public.deck_admin_audit_log (deck_id, actor_id, action, metadata)
  values (p_deck_id, actor, 'deck_version_created', jsonb_build_object('version', new_version, 'version_id', new_version_id));
  return new_version;
end;
$$;

