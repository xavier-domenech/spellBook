  exists (
    select 1 from public.deck_versions
    join public.decks on decks.id = deck_versions.deck_id
    where deck_versions.id = deck_cards.deck_version_id and (
      decks.owner_id = (select auth.uid())
      or (
        decks.moderation_status = 'visible' and decks.archived_at is null
        and decks.visibility in ('public', 'unlisted')
      )
    )
  )
);
create policy "admins read every deck card" on public.deck_cards for select to authenticated
using (public.is_admin());

