create function public.admin_set_deck_moderation(p_deck_id uuid, p_hidden boolean, p_reason text default '')
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare actor uuid := (select auth.uid());
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if p_hidden and char_length(trim(coalesce(p_reason, ''))) < 3 then raise exception 'Moderation reason required'; end if;
  update public.decks
  set moderation_status = (case when p_hidden then 'hidden' else 'visible' end)::public.deck_moderation_status,
      moderation_reason = case when p_hidden then trim(p_reason) else '' end,
      moderated_at = case when p_hidden then now() else null end,
      moderated_by = case when p_hidden then actor else null end
  where id = p_deck_id;
  if not found then raise exception 'Deck not found'; end if;
  insert into public.deck_admin_audit_log (deck_id, actor_id, action, reason)
  values (p_deck_id, actor, case when p_hidden then 'deck_hidden' else 'deck_restored' end, trim(coalesce(p_reason, '')));
end;
$$;

